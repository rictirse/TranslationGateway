    user_prompt         text,
    history             text,
    response_raw        text,
    keyword_term_ids    text,
    fix_ids             text,
    prompt_tokens       integer,
    completion_tokens   integer,
    latency_ms          integer,
    outcome             text NOT NULL,
    created_at          timestamptz NOT NULL DEFAULT now()
