-- 聽錯字修正：Whisper 把詞彙卡名詞聽錯的寫法 → 正確寫法；Approved 的才套用（前處理：修正原文再翻譯）
-- right 是 PostgreSQL 保留字，欄位名稱用 right_text（wrong 為了一致用 wrong_text），Dapper 對應時以別名轉成 Right／Wrong
CREATE TABLE IF NOT EXISTS mishearing_fixes (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    card_id     bigint NOT NULL REFERENCES glossary_cards(id) ON DELETE CASCADE,
    term_id     bigint NOT NULL REFERENCES glossary_terms(id) ON DELETE CASCADE,
    kind        text NOT NULL DEFAULT 'Pre',
    wrong_text  text NOT NULL,
    right_text  text NOT NULL,
    status      text NOT NULL DEFAULT 'Pending',
    evidence    text,
    occurrences integer NOT NULL DEFAULT 1,
    created_at  timestamptz NOT NULL DEFAULT now(),
    updated_at  timestamptz,
    UNIQUE (term_id, kind, wrong_text)
);
CREATE INDEX IF NOT EXISTS ix_mishearing_fixes_status ON mishearing_fixes(status);
COMMENT ON TABLE  mishearing_fixes IS '聽錯字修正：Whisper 把詞彙卡名詞聽錯的寫法 → 正確寫法；Approved 的才套用（前處理：修正原文再翻譯）';
COMMENT ON COLUMN mishearing_fixes.id IS '流水號';
COMMENT ON COLUMN mishearing_fixes.card_id IS '所屬詞彙卡';
COMMENT ON COLUMN mishearing_fixes.term_id IS '對應的名詞（一個名詞可有多個錯字）';
COMMENT ON COLUMN mishearing_fixes.kind IS 'Pre（前處理：修正原文）| Post（後處理：修正譯文，之後才有）';
COMMENT ON COLUMN mishearing_fixes.wrong_text IS '聽錯的寫法（至少 2 個字）';
COMMENT ON COLUMN mishearing_fixes.right_text IS '正確寫法（通常等於名詞的 Source）';
COMMENT ON COLUMN mishearing_fixes.status IS 'Pending（待審核）| Approved（已核准，會套用）；駁回直接刪除';
COMMENT ON COLUMN mishearing_fixes.evidence IS '證據：出現錯字的字幕原句（最多 200 字）';
COMMENT ON COLUMN mishearing_fixes.occurrences IS '被探勘到的次數';
COMMENT ON COLUMN mishearing_fixes.created_at IS '建立時間';
COMMENT ON COLUMN mishearing_fixes.updated_at IS '最後一次累加或審核的時間';

-- YouTube 生成式字幕快取：每支影片每種語言一筆；同一支影片再開時直接載入，不再下載。查不到字幕的影片不寫入
CREATE TABLE IF NOT EXISTS youtube_captions (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    video_id     text NOT NULL,
    language     text NOT NULL,
    is_auto      boolean NOT NULL,
    client_name  text,
    cue_count    integer NOT NULL,
    cues_json    text NOT NULL,
    created_at   timestamptz NOT NULL DEFAULT now(),
    last_used_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (video_id, language)
);
CREATE INDEX IF NOT EXISTS ix_youtube_captions_last_used_at ON youtube_captions(last_used_at);
COMMENT ON TABLE  youtube_captions IS 'YouTube 生成式字幕快取，每支影片每種語言一筆；同一支影片再開時直接載入，不再下載。查不到字幕的影片不寫入';
COMMENT ON COLUMN youtube_captions.video_id IS 'YouTube 影片 ID（11 碼）';
COMMENT ON COLUMN youtube_captions.language IS '字幕語言代碼，例如 ja';
COMMENT ON COLUMN youtube_captions.is_auto IS 'true 是 YouTube 自動產生（asr），false 是人工上傳';
COMMENT ON COLUMN youtube_captions.client_name IS '下載時使用的用戶端身分（VISIONOS、IOS）';
COMMENT ON COLUMN youtube_captions.cue_count IS '字幕段數';
COMMENT ON COLUMN youtube_captions.cues_json IS '字幕內容 JSON 陣列 [{"s":開始毫秒,"d":長度毫秒,"t":"文字"}]，依開始時間排序';
COMMENT ON COLUMN youtube_captions.created_at IS '寫入時間，之後依保存期限清除時的依據';
COMMENT ON COLUMN youtube_captions.last_used_at IS '最後一次從快取載入的時間';

-- 生成式字幕經 AI 重新斷句、校正後的句子（前處理結果）；讀寫程式之後的卡片處理
