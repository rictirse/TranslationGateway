CREATE INDEX IF NOT EXISTS ix_settings_snapshots_last_used_at ON settings_snapshots(last_used_at);
COMMENT ON TABLE  settings_snapshots IS '設定快照：翻譯設定的 JSON 全文，內容雜湊去重；過期時一併清除';
COMMENT ON COLUMN settings_snapshots.content IS '翻譯設定的 JSON 全文';
COMMENT ON COLUMN settings_snapshots.content_hash IS '內容的 SHA-256';
COMMENT ON COLUMN settings_snapshots.created_at IS '寫入時間';
COMMENT ON COLUMN settings_snapshots.last_used_at IS '最後一次被（Ensure 命中）使用的時間，過期清除的依據';

-- 模型呼叫紀錄：每次呼叫模型一列（回溯分析用）；過期時一併清除
