-- TranslationGateway 資料庫結構（PostgreSQL）
-- 程式啟動時整份執行（嵌入資源），在 CREATE SCHEMA 之後、以連線的 Search Path 指向設定的 schema。
-- 只能用 IF NOT EXISTS 新增，不得刪除或改動既有資料；COMMENT ON 每次重跑會覆寫成最新說明。
-- SQLite 版本見 sqlite-schema.sql，兩份必須同步維護。

CREATE TABLE IF NOT EXISTS translation_cache (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_text text NOT NULL UNIQUE,
    target_text text,
    is_manual   boolean NOT NULL DEFAULT false,
    last_used   timestamptz
);
COMMENT ON TABLE  translation_cache IS '翻譯快取：同一句原文只翻一次';
COMMENT ON COLUMN translation_cache.source_text IS '快取索引：PotPlayer 送來的原文（原文修正之後）';
COMMENT ON COLUMN translation_cache.target_text IS '譯文（譯名修正之前；輸出時才套用譯名修正）';
COMMENT ON COLUMN translation_cache.is_manual IS 'true = 使用者手動修正過，不會被自動覆寫或刪除';
COMMENT ON COLUMN translation_cache.last_used IS '最後寫入或命中的時間';

CREATE TABLE IF NOT EXISTS glossary_cards (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind           text NOT NULL,
    name           text NOT NULL UNIQUE,
    parent_id      bigint REFERENCES glossary_cards(id) ON DELETE SET NULL,
    channel_id     text,
    channel_handle text,
    aliases        text,
    description    text,
    source_url     text,
    status         text NOT NULL DEFAULT 'Pending',
    created_at     timestamptz NOT NULL DEFAULT now(),
    updated_at     timestamptz
);
COMMENT ON TABLE  glossary_cards IS '詞彙卡：角色、團體、遊戲共用同一種卡';
COMMENT ON COLUMN glossary_cards.kind IS 'Character（角色）| Group（團體）| Game（遊戲）';
COMMENT ON COLUMN glossary_cards.name IS '卡名：日文原名、團體名或遊戲名';
COMMENT ON COLUMN glossary_cards.parent_id IS '上層卡（角色所屬團體）；角色卡生效時一起生效';
COMMENT ON COLUMN glossary_cards.channel_id IS 'YouTube 頻道 ID（UC 開頭）';
COMMENT ON COLUMN glossary_cards.channel_handle IS 'YouTube @handle；一鍵開台時用來自動套用角色卡';
COMMENT ON COLUMN glossary_cards.description IS '說明；遊戲卡的說明是簡介（最多 100 字），生效時會放進 system prompt，其他種類只給人看';
COMMENT ON COLUMN glossary_cards.source_url IS '資料來源網址';
COMMENT ON COLUMN glossary_cards.status IS 'Pending（待審核）| Approved（已核准）| Rejected（已拒絕，不使用）';

