COMMENT ON COLUMN subtitle_log.model_latency_ms IS '模型耗時（毫秒）；沒有呼叫模型時為 0';
COMMENT ON COLUMN subtitle_log.is_edited IS 'true = 使用者在 Dashboard 手動改過原文或譯文';
COMMENT ON COLUMN subtitle_log.is_deleted IS 'true = 使用者在 Dashboard 刪除；只做標記，資料保留';
COMMENT ON COLUMN subtitle_log.updated_at IS '最後一次編輯或刪除的時間';

