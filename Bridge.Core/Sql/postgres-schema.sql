COMMENT ON TABLE  caption_sentences IS '生成式字幕經 AI 重新斷句、校正後的句子（前處理結果）';
COMMENT ON COLUMN caption_sentences.caption_id IS '所屬字幕';
COMMENT ON COLUMN caption_sentences.start_ms IS '句子在影片中的開始毫秒';
COMMENT ON COLUMN caption_sentences.end_ms IS '句子在影片中的結束毫秒';
COMMENT ON COLUMN caption_sentences.raw_text IS '對應的原始字幕文字';
COMMENT ON COLUMN caption_sentences.text IS '前處理後的日文';
COMMENT ON COLUMN caption_sentences.model IS '前處理使用的模型';
COMMENT ON COLUMN caption_sentences.created_at IS '寫入時間';

-- prompt 版本（模板）：同一種 kind 的每次修改各一列，(kind, 內容雜湊) 去重；永不刪除
CREATE TABLE IF NOT EXISTS prompt_templates (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind         text NOT NULL,
    content      text NOT NULL,
    content_hash text NOT NULL,
    origin       text NOT NULL,
    app_version  text,
    created_at   timestamptz NOT NULL DEFAULT now(),
    UNIQUE (kind, content_hash)
);
COMMENT ON TABLE  prompt_templates IS 'prompt 版本（模板）：同一種 kind 的每次修改各一列，(kind, 內容雜湊) 去重；永不刪除';
COMMENT ON COLUMN prompt_templates.kind IS '種類：LiveSystem（直播 system prompt）| VodBatch（錄影批次）| MiningExtract（探勘拆解）| MiningCompose（探勘整理）| Mishearing（聽錯字）| TermDiscovery（遊戲用語）| TermImport（貼上整理）| CaptionPreprocess（字幕前處理）';
COMMENT ON COLUMN prompt_templates.content IS '模板全文';
COMMENT ON COLUMN prompt_templates.content_hash IS '內容的 SHA-256（AuditHash.Of，小寫 hex 64 字）';
COMMENT ON COLUMN prompt_templates.origin IS '來源：Default（內建預設）| User（使用者修改）';
COMMENT ON COLUMN prompt_templates.app_version IS '第一次寫入時的程式版本';
COMMENT ON COLUMN prompt_templates.created_at IS '寫入時間';

-- prompt 快照：組好的 system prompt 全文，內容雜湊去重；過期時一併清除
CREATE TABLE IF NOT EXISTS prompt_snapshots (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    template_id  bigint REFERENCES prompt_templates(id) ON DELETE SET NULL,
    content      text NOT NULL,
    content_hash text NOT NULL UNIQUE,
    created_at   timestamptz NOT NULL DEFAULT now(),
    last_used_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_prompt_snapshots_last_used_at ON prompt_snapshots(last_used_at);
COMMENT ON TABLE  prompt_snapshots IS 'prompt 快照：組好的 system prompt 全文，內容雜湊去重；過期時一併清除';
COMMENT ON COLUMN prompt_snapshots.template_id IS '來源的 prompt 版本；查不到時為空（去重只看內容，不參與比對）';
COMMENT ON COLUMN prompt_snapshots.content IS '組好的 system prompt 全文';
COMMENT ON COLUMN prompt_snapshots.content_hash IS '內容的 SHA-256';
COMMENT ON COLUMN prompt_snapshots.created_at IS '寫入時間';
COMMENT ON COLUMN prompt_snapshots.last_used_at IS '最後一次被（Ensure 命中）使用的時間，過期清除的依據';

-- 設定快照：翻譯設定的 JSON 全文，內容雜湊去重；過期時一併清除
